
# Define assets
bank_account = 5000.00
savings = 3000.00
car_value = 12000.00

# Define debts
credit_card = 1000.00
student_loan = 4000.00
car_loan = 5000.00

# Calculate total assets and debts
total_assets = bank_account + savings + car_value
total_debts = credit_card + student_loan + car_loan

# Calculate net worth
net_worth = total_assets - total_debts

# Display results
print(f"Your total assets are {total_assets}")
print(f"Your total debts are {total_debts}")
print(f"Your net worth is {net_worth}")
